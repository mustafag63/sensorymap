-- ---------------------------------------------------------------
-- Kriter doğrulaması (SPEC §2). src/data/kriterler.js ile aynı liste;
-- değişince ikisi birlikte güncellenir.
-- ---------------------------------------------------------------
create function public.gecerli_kriter(p_nesne_turu text, p_alan text, p_deger text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select case p_nesne_turu
    when 'giris' then case p_alan
      when 'giris_turu'        then p_deger in ('ana', 'yan', 'acil_cikis')
      when 'basamaksiz'        then p_deger in ('var', 'yok')
      when 'rampa'             then p_deger in ('uygun', 'var_ama_dik', 'yok', 'gerek_yok')
      when 'kapi_genisligi_cm' then p_deger ~ '^[0-9]{1,3}$'
      when 'kapi_tipi'         then p_deger in ('otomatik', 'el_ile_hafif', 'el_ile_agir', 'doner')
      when 'acik_saatler'      then char_length(btrim(p_deger)) >= 1 and char_length(p_deger) <= 200
      else false
    end
    when 'mekan' then case p_alan
      when 'asansor'         then p_deger in ('var_calisiyor', 'var_calismiyor', 'yok', 'gerek_yok')
      when 'ic_kapi_cm'      then p_deger ~ '^[0-9]{1,3}$'
      when 'erisilebilir_wc' then p_deger in ('var', 'yok')
      when 'gurultu_yogun'   then p_deger in ('sessiz', 'orta', 'gurultulu')
      when 'gurultu_sakin'   then p_deger in ('sessiz', 'orta', 'gurultulu')
      when 'isik'            then p_deger in ('dogal', 'led', 'floresan', 'los')
      when 'oturma'          then p_deger in ('seyrek', 'orta', 'sik')
      when 'sessiz_alan'     then p_deger in ('var', 'yok')
      when 'muzik'           then p_deger in ('yok', 'dusuk', 'yuksek')
      else false
    end
    else false
  end;
$$;

-- Değer boşken (veri_yok) yalnızca anahtarın geçerliliği denetlenir.
create function public.gecerli_kriter_anahtari(p_nesne_turu text, p_alan text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select case p_nesne_turu
    when 'giris' then p_alan in ('giris_turu', 'basamaksiz', 'rampa', 'kapi_genisligi_cm', 'kapi_tipi', 'acik_saatler')
    when 'mekan' then p_alan in ('asansor', 'ic_kapi_cm', 'erisilebilir_wc', 'gurultu_yogun', 'gurultu_sakin',
                                 'isik', 'oturma', 'sessiz_alan', 'muzik')
    else false
  end;
$$;

-- ---------------------------------------------------------------
-- Bina → Giriş → Mekân (SPEC §1)
-- ---------------------------------------------------------------
create table public.binalar (
  id        bigint generated by default as identity primary key,
  ad        text not null check (char_length(btrim(ad)) between 1 and 120),
  enlem     double precision not null check (enlem between -90 and 90),
  boylam    double precision not null check (boylam between -180 and 180),
  notlar    text check (char_length(notlar) <= 1000),
  olusturma timestamptz not null default now()
);

create table public.girisler (
  id        bigint generated by default as identity primary key,
  bina_id   bigint not null references public.binalar (id) on delete cascade,
  ad        text not null check (char_length(btrim(ad)) between 1 and 120),
  enlem     double precision not null check (enlem between -90 and 90),
  boylam    double precision not null check (boylam between -180 and 180),
  olusturma timestamptz not null default now()
);
create index girisler_bina_idx on public.girisler (bina_id);

create table public.mekanlar (
  id        bigint generated by default as identity primary key,
  bina_id   bigint not null references public.binalar (id) on delete cascade,
  ad        text not null check (char_length(btrim(ad)) between 1 and 120),
  tur       text not null check (tur in ('kutuphane', 'yemekhane', 'calisma_salonu', 'kafe', 'diger')),
  kat       integer not null default 0 check (kat between -5 and 50),  -- 0 = giriş katı
  enlem     double precision not null check (enlem between -90 and 90),
  boylam    double precision not null check (boylam between -180 and 180),
  foto_url  text check (foto_url is null or foto_url ~ '^https://'),
  olusturma timestamptz not null default now()
);
create index mekanlar_bina_idx on public.mekanlar (bina_id);

-- ---------------------------------------------------------------
-- Kriter değerleri ve durumları (SPEC §3). İstemci yazamaz;
-- yalnızca trigger'lar (security definer) ve ekip üyeleri yazar.
-- ---------------------------------------------------------------
create table public.alanlar (
  id           bigint generated by default as identity primary key,
  nesne_turu   text not null check (nesne_turu in ('giris', 'mekan')),
  nesne_id     bigint not null,
  alan_adi     text not null,
  deger        text,
  durum        text not null default 'veri_yok' check (durum in ('veri_yok', 'teyitsiz', 'dogrulanmis')),
  kaynak       text check (kaynak in ('ekip', 'kullanici')),
  olcum_zamani timestamptz,  -- gürültü günün saatine göre değiştiği için
  guncelleme   timestamptz not null default now(),
  unique (nesne_turu, nesne_id, alan_adi),
  check (public.gecerli_kriter_anahtari(nesne_turu, alan_adi)),
  check (deger is null or public.gecerli_kriter(nesne_turu, alan_adi, deger)),
  check ((durum = 'veri_yok') = (deger is null))
);

-- ---------------------------------------------------------------
-- Kullanıcı katkıları. anonim_id = auth.uid() (anonymous sign-in, SPEC §6.2)
-- ---------------------------------------------------------------
create table public.bildirimler (
  id         bigint generated by default as identity primary key,
  nesne_turu text not null check (nesne_turu in ('giris', 'mekan')),
  nesne_id   bigint not null,
  alan_adi   text not null,
  deger      text not null,
  anonim_id  uuid not null default auth.uid(),
  tarih      timestamptz not null default now(),
  durum      text not null default 'bekliyor' check (durum in ('bekliyor', 'dogrulandi')),
  check (public.gecerli_kriter(nesne_turu, alan_adi, deger))
);
create index bildirimler_nesne_idx on public.bildirimler (nesne_turu, nesne_id, alan_adi);

create table public.teyitler (
  id          bigint generated by default as identity primary key,
  bildirim_id bigint not null references public.bildirimler (id) on delete cascade,
  anonim_id   uuid not null default auth.uid(),
  tarih       timestamptz not null default now(),
  unique (bildirim_id, anonim_id)  -- aynı kişi aynı bildirimi iki kez teyit edemez
);

create table public.hata_bildirimleri (
  id         bigint generated by default as identity primary key,
  nesne_turu text not null check (nesne_turu in ('giris', 'mekan')),
  nesne_id   bigint not null,
  aciklama   text not null check (char_length(btrim(aciklama)) between 1 and 1000),
  tarih      timestamptz not null default now(),
  cozuldu    boolean not null default false
);

-- ---------------------------------------------------------------
-- Ekip üyeleri: panelde yazma yetkisi olan hesaplar (elle eklenir).
-- Anonim oturumlar da "authenticated" rolünde olduğu için ekip
-- yetkisi bu tabloyla ayrılır.
-- ---------------------------------------------------------------
create table public.ekip_uyeleri (
  kullanici_id uuid primary key references auth.users (id) on delete cascade,
  eklenme      timestamptz not null default now()
);
